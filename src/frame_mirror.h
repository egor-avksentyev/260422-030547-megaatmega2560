// frame_mirror.h/.cpp — ЭКСПЕРИМЕНТ (ветка experiment/frame-mirror-serial3, НЕ main):
// пиксель-в-пиксель зеркало OLED на веб-странице ESP32 через ОТДЕЛЬНЫЙ, выделенный
// аппаратный UART (Serial3, пины TX3=14/RX3=15 — RX3 физически никуда не подключаем, канал
// только Mega->ESP32), на повышенной скорости (FRAME_MIRROR_BAUD, hardware_settings.h) —
// специально НЕ Serial2 (существующий, протестированный линк с ESP32: CMD:/META:/PLAY:/
// POWER:/TEMP:/VOLT:/...), чтобы физически не иметь возможности задеть его или разделяемый
// с ним тайминг.
//
// Формат — простой бинарный (не текстовые строки, как у Serial2 — там '\n'-разделитель, тут
// его нет и быть не может, раз этим каналом больше никто не пользуется):
//   0xAA 0x55 <1024 байта буфера u8g2 (128x64/8, tile-формат)> <1 байт ID иконки> <1 байт
//   ID экрана, см. FRAME_MIRROR_SCREEN_* ниже> <1 байт XOR-чексумма (по 1026 байтам: буфер +
//   иконка + экран)>
// Чексумма — только чтобы отбросить визуально "битый" кадр целиком (не показывать кашу на
// экране), не для гарантированной доставки — раз в несколько кадров пропустить один кадр
// незаметно для человеческого глаза.
//
// ID иконки — НЕ для попытки синхронизировать саму анимацию по UART (та крутится в фоне
// каждые MENU_ICON_FRAME_DELAY_MS независимо от полных перерисовок, гонять кадр на каждый
// тик анимации означало бы слать его непрерывно, а не только по требованию, см. обсуждение в
// чате) — а чтобы веб-страница знала, КАКОЙ набор кадров крутить у себя САМОСТОЯТЕЛЬНО, своим
// локальным таймером (те же самые кадры, скопированные из animations/*_animation.cpp, см.
// ICON_B64 в web_control.cpp ESP32-репозитория) — синхронности между "какой кадр анимации
// прямо сейчас на Mega" и "какой кадр анимации прямо сейчас в браузере" НЕ требуется
// (осознанное решение пользователя), важно только КАКОЙ набор кадров (какая иконка) сейчас
// активна на карусели меню
#define FRAME_MIRROR_ICON_BASS_HIGH_VOLUME 0
#define FRAME_MIRROR_ICON_VU_METER 1
#define FRAME_MIRROR_ICON_BYPASS 2
#define FRAME_MIRROR_ICON_DIMMER 3
#define FRAME_MIRROR_ICON_COLOR 4
#define FRAME_MIRROR_ICON_SOURCE 5
#define FRAME_MIRROR_ICON_EQ 6
#define FRAME_MIRROR_ICON_INFO 7
#define FRAME_MIRROR_ICON_NONE 255 // Не карусель меню (экран настройки конкретного пункта,
                                    // Now Playing, displayMessage()) — иконки нет вообще

// ID экрана — отдельно от иконки: нужен, чтобы веб-страница знала, когда рисовать поверх
// зеркала СВОЙ локально просимулированный прогресс-бар трека (та же причина, что у иконок —
// updateNowPlayingProgress() тикает частичным updateDisplayArea(), не полным sendBuffer(), в
// зеркале не подключён и подключаться не должен — тикать чаще раза в секунду означало бы
// слать кадр непрерывно, пока играет музыка, а не только по требованию). Позиция/длина трека
// у веб-страницы и так уже есть (тот же /track, что она использует для своего собственного,
// отдельного индикатора) — не хватало только "сейчас показан именно экран Now Playing"
#define FRAME_MIRROR_SCREEN_OTHER 0
#define FRAME_MIRROR_SCREEN_NOW_PLAYING 1
// Та же идея — Mute тоже прекращает слать полные кадры после первого (см. mute_animation.cpp,
// needsFullClear) и дальше крутит анимацию частичными updateDisplayArea(), в зеркало не
// попадающими. Веб-страница по этому ID сама крутит те же 18 кадров 48x48 локально (MUTE_B64,
// web_control.cpp ESP32-репозитория), поверх (изначально верно нарисованного один раз) чёрного
// фона — синхронности с реальным кадром на Mega, как и у иконок, не требуется
#define FRAME_MIRROR_SCREEN_MUTE 2
//
// Почему это может быть безопаснее прежней попытки (см. память проекта,
// project_frame_mirror_experiment_rejected — та же идея на общем Serial2, в hex, 115200 бод,
// ~180мс блокировки loop() на кадр, отклонена из-за реального стутора мотора/пульта): здесь
// отдельный физический провод (не может столкнуться по времени с другими сообщениями Serial2)
// + сырой бинарный формат (вдвое меньше байт, чем hex) + FRAME_MIRROR_BAUD выше 115200 — при
// 500000 бод и 128x64 буфере блокировка падает примерно до ~20мс на кадр
// (1027 байт * 10 бит/байт / 500000 бод). Всё ещё блокирующий вызов (Serial.write() на AVR не
// бывает неблокирующим), просто короче — ниже почти всех тайм-аутов в прошивке
// (SLIDER_MOTOR_IDLE_TIMEOUT=260мс, повтор ИК ~114мс, DISPLAY_REDRAW_MIN_GAP_MS=50мс), поэтому
// шанс реально помешать моторам/пульту заметно меньше — но гарантии ноль, отсюда отдельная
// ветка, а не main, пока не проверено на реальном железе.
// ============================================================================

