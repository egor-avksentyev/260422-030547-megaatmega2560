#pragma once

// ============================================================================
// bass_volume_high_animation.h — крутящийся индикатор "doughnut chart" в крайней
// левой части экрана главного меню (drawMenu(), display_logic.cpp), показывается
// только когда currentMenuItem — Bass/High/Volume. В отличие от mute_animation.h/
// unmute_animation.h — не одноразовая: сама решает по таймеру, когда переключить кадр.
//
// Два способа отрисовки:
// - drawBassVolumeHighAnim(x, y) — рисует кадр В УЖЕ ОЧИЩЕННЫЙ буфер, ничего не
//   отправляет сама. Только для использования ВНУТРИ drawMenu() (там и так идёт
//   полная перерисовка+sendBuffer()).
// - animateBassVolumeHighIconPartial(x, y) — для фонового "кручения", пока
//   пользователь просто сидит на пункте без действий. Не трогает остальной буфер и
//   не гонит через SPI весь экран (1024 байта) — только тайлы (8x8px блоки) под
//   самой иконкой, через u8g2.updateDisplayArea(). Раньше для этого дёргали
//   drawMenu() целиком по таймеру, но это создавало на глазах ставший заметным риск
//   для навигации с пульта на Bass/High/Volume (полная передача экрана иногда
//   "перебивала" передачу от только что нажатой Right/Left, и переключение пункта
//   не отображалось с первого нажатия) — частичное обновление гоняет в разы меньше
//   данных, поэтому конфликтовать с навигацией ей физически намного сложнее.
// ============================================================================

void drawBassVolumeHighAnim(int x, int y);
void animateBassVolumeHighIconPartial(int x, int y);
