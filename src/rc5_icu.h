#pragma once

// ============================================================================
// rc5_icu.h/.cpp — рабочий, ПРОДАКШН путь приёма RC5 (подключён из
// remote_control.cpp: initRemoteControl()/handleRemoteInput()), заменивший собой
// библиотеку IRremote — та таймерным опросом пина периодически теряла кадры,
// если приём совпадал по времени с NeoPixel.show() (см. ниже почему).
//
// Отличие от IRremote (таймерный опрос пина каждые 50мкс) и от классических
// самодельных декодеров на внешнем прерывании (например pinkeen/avr-rc5,
// GPLv3, https://github.com/pinkeen/avr-rc5 — оттуда взята сама таблица
// переходов состояний, алгоритм Guy Carpenter/Clearwater Software, 2001) —
// здесь тайминг фронта берётся из ICR4 (Input Capture Register таймера 4),
// а не из "живого" TCNT, прочитанного внутри обработчика внешнего прерывания.
// ICR4 защёлкивается АППАРАТНО в момент самого фронта, независимо от того,
// замаскированы ли в этот момент прерывания (cli() внутри Adafruit_NeoPixel::
// show()) — обработчик может выполниться позже, но прочитает точное значение,
// а не смещённое на время маскировки. Окно маскировки одного кольца (~360мкс
// на 12 светодиодов) короче минимального расстояния между фронтами RC5
// (~889мкс), поэтому за одно окно физически не может произойти больше одного
// фронта — а значит ICR4 не будет перезаписан вторым фронтом раньше, чем его
// прочитает обработчик. Подтверждено на живом железе (ветка
// experiment/icu-rc5-decoder): из 28 кадров подряд при работающих кольцах
// IRremote потерял 3, этот декодер — ни одного.
//
// Пин: ICP4 = Arduino-пин 49 (PL0) на Mega — единственный вход захвата Timer4,
// ничем больше в проекте не занят. Старый IR_PIN=19 (hardware_settings.h)
// прошивкой больше не читается — провод можно оставить как есть или отпаять.
// ============================================================================

